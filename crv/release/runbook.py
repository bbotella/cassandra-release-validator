"""The per-project runbook in the skill's release-process.md, generated from the step definitions.

`cut-release runbook` prints it; `cut-release runbook --write` refreshes the generated section of the
file. A unit test fails when the file and the steps disagree, so the two can't drift.
"""

from __future__ import annotations

from pathlib import Path

from ..projects import by_name
from . import steps as steps_mod

RUNBOOK = Path(__file__).resolve().parents[2] / ".claude" / "skills" / "cassandra-release-manager" / "references" \
    / "release-process.md"
BEGIN = "<!-- BEGIN generated by `./cut-release runbook --write` from crv/release/steps: do not edit by hand -->"
END = "<!-- END generated runbook -->"

OUT_OF_BAND = {
    "reroll": "cancel the attempt: removes the tentative tag and the dist/dev directory, then the next attempt starts",
    "check-upstream": "compare the official scripts upstream with the versions reviewed in docs/parity.md",
    "cleanup": "rehearsals only (`--rehearsal`): delete the sandbox and its throwaway signing key",
}


def _cell(text: str) -> str:
    # \< keeps <version> visible where Markdown is rendered, and reads the same where it isn't
    return text.replace("|", "\\|").replace("<", "\\<").replace("\n", " ")


def render() -> str:
    steps_mod.load_all()
    out = [
        "Each outward step is a dry run unless `--confirm` is given. `cut-release <project> <version> plan` shows",
        "where a release stands. Steps run in this order; a step refuses to run before the ones above it.",
        "In *Replicates*, `CP`/`CF` are cassandra-release/prepare_release.sh and finish_release.sh, `SP`/`SF`",
        "the Sidecar ones and `AP`/`AF` the Analytics ones, with line numbers (`docs/parity.md` maps them).",
        "",
    ]
    for key, order in steps_mod.PLANS.items():
        project = by_name(key)
        out += [f"### {project.display}", "", "| # | Step | Kind | What it does | Your part | Replicates |",
                "|---|---|---|---|---|---|"]
        for n, name in enumerate(order, 1):
            step = steps_mod.lookup(name, key)
            if step is None:
                out.append(f"| {n} | `{name}` | | *not implemented yet* | | |")
                continue
            kind = "outward" if step.outward else "local"
            out.append(f"| {n} | `{name}` | {kind} | {_cell(step.summary)} | {_cell(step.you_do)} | "
                       f"{_cell(step.replicates)} |")
        out.append("")
    out += ["Out of band, for every project:", ""]
    out += [f"- `{name}`: {text}" for name, text in OUT_OF_BAND.items()]
    return "\n".join(out) + "\n"


def current() -> str | None:
    """The generated section as it is in the file, or None without the markers."""
    text = RUNBOOK.read_text()
    if BEGIN not in text or END not in text:
        return None
    return text.split(BEGIN, 1)[1].split(END, 1)[0].strip("\n") + "\n"


def write() -> bool:
    """Refreshes the generated section. Returns whether the file changed."""
    text = RUNBOOK.read_text()
    head, rest = text.split(BEGIN, 1)
    tail = rest.split(END, 1)[1]
    new = f"{head}{BEGIN}\n{render()}{END}{tail}"
    if new == text:
        return False
    RUNBOOK.write_text(new)
    return True
